-- How many accounts have alternate contacts?
SELECT
    'Accounts with alternate contacts' AS metric,
    COUNT(DISTINCT r.account_id) AS count_val
FROM TBRDP_DW_PROD.IM_RPT.TMP_RENEWAL_CONTACTS r
JOIN TBRDP_DW_PROD.IM_RPT.V_ODS_SALESFORCE_CONTACT c
    ON r.account_id = c.ACCOUNT_ID
    AND c.SYSTEM_CURRENT_FLAG = 'Y'
    AND c.IS_DELETED = FALSE
    AND c.ID != r.primary_contact_id

UNION ALL

-- How many primary contacts have bounced emails?
SELECT
    'Primary contacts with bounced email' AS metric,
    COUNT(*) AS count_val
FROM TBRDP_DW_PROD.IM_RPT.TMP_RENEWAL_CONTACTS r
JOIN TBRDP_DW_PROD.IM_RPT.V_ODS_SALESFORCE_CONTACT c
    ON c.ID = r.primary_contact_id
    AND c.SYSTEM_CURRENT_FLAG = 'Y'
WHERE c.IS_EMAIL_BOUNCED = TRUE

UNION ALL

