--- Cortex Search Services  

CREATE OR REPLACE CORTEX SEARCH SERVICE TBRDP_DW_PROD.IM_RPT.OPPORTUNITY_SEARCH_SERVICE
    ON SEARCHABLE_CONTENT
    ATTRIBUTES OPPORTUNITY_NAME, ACCOUNT_ID, STAGE_NAME, AMOUNT, CLOSE_DATE, HEALTH_CATEGORY, HEALTH_SCORE, OWNER_ID
    WAREHOUSE = TBRDP_DW_CORTEX_XS_WH
    TARGET_LAG = '6 hour'
    EMBEDDING_MODEL = 'snowflake-arctic-embed-l-v2.0'
    COMMENT = 'Semantic search for opportunity context - rebuilt on permanent tables'
AS (
    SELECT 
        OPPORTUNITY_ID,
        OPPORTUNITY_NAME,
        ACCOUNT_ID,
        STAGE_NAME,
        AMOUNT,
        CLOSE_DATE,
        SEARCHABLE_CONTENT,
        HEALTH_CATEGORY,
        HEALTH_SCORE,
        OWNER_ID,
        CREATED_DATE,
        LAST_MODIFIED_DATE
    FROM TBRDP_DW_PROD.IM_RPT.T_OPPORTUNITY_SEARCH_SOURCE
);

-- 2. Update the refresh task to match the 12-hour cadence
CREATE OR REPLACE TASK TBRDP_DW_PROD.IM_RPT.REFRESH_OPPORTUNITY_SEARCH_SOURCE
    WAREHOUSE = TBRDP_DW_CORTEX_XS_WH
    SCHEDULE = '600 MINUTE'
AS
INSERT OVERWRITE INTO TBRDP_DW_PROD.IM_RPT.T_OPPORTUNITY_SEARCH_SOURCE
SELECT * FROM TBRDP_DW_PROD.IM_RPT.V_OPPORTUNITY_CONTEXT_SEARCH;

-- 3. Resume the task
ALTER TASK TBRDP_DW_PROD.IM_RPT.REFRESH_OPPORTUNITY_SEARCH_SOURCE RESUME;