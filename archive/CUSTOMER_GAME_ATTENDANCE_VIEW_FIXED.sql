CREATE OR REPLACE VIEW TBRDP_DW_PROD.IM_RPT.V_CUSTOMER_GAME_ATTENDANCE AS
SELECT 
    t.FINANCIAL_PATRON_ACCOUNT_ID,
    COUNT(DISTINCT x.GAMEPK) AS GAMES_ATTENDED,
    COUNT(DISTINCT CASE WHEN g.RAYS_WIN = TRUE THEN x.GAMEPK END) AS GAMES_WON,
    COUNT(DISTINCT CASE WHEN g.RAYS_WIN = FALSE THEN x.GAMEPK END) AS GAMES_LOST,
    ROUND(COUNT(DISTINCT CASE WHEN g.RAYS_WIN = TRUE THEN x.GAMEPK END) * 100.0 / NULLIF(COUNT(DISTINCT x.GAMEPK), 0), 1) AS WIN_PCT_ATTENDED,
    SUM(t.PRICE) AS TOTAL_TICKET_SPEND,
    ROUND(AVG(t.PRICE), 2) AS AVG_TICKET_PRICE,
    MIN(x.GAME_DATE) AS FIRST_GAME_DATE,
    MAX(x.GAME_DATE) AS LAST_GAME_DATE,
    COUNT(DISTINCT t.SEASON_YEAR) AS SEASONS_ATTENDED_COUNT,
    ARRAY_TO_STRING(ARRAY_AGG(DISTINCT t.SEASON_YEAR) WITHIN GROUP (ORDER BY t.SEASON_YEAR), ', ') AS SEASONS_ATTENDED
FROM TBRDP_DW_PROD.IM_RPT.V_SBL_GCP_TDC_REGULAR_SEASON_TICKET_DETAIL t
JOIN TBRDP_DW_PROD.IM_RPT.T_EVENT_CROSSWALK x ON t.EVENT_ID = x.EVENT_ID
JOIN TBRDP_DW_PROD.IM_RPT.T_GAME_RESULTS g ON x.GAMEPK = g.GAMEPK
WHERE t.SYSTEM_CURRENT_FLAG = 'Y'
  AND t.SEASON_YEAR >= 2023
GROUP BY t.FINANCIAL_PATRON_ACCOUNT_ID;
